#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { swe_calc_ut, swe_julday, swe_sidtime } from './load-swe-node.mjs';

const SE_GREG_CAL = 1;
const SE_ECL_NUT = -1;
const SEFLG_MOSEPH = 4;
const PLANETS = [
  [0, 'Sun'],
  [1, 'Moon'],
  [2, 'Mercury'],
  [3, 'Venus'],
  [4, 'Mars'],
  [5, 'Jupiter'],
  [6, 'Saturn'],
  [7, 'Uranus'],
  [8, 'Neptune'],
  [9, 'Pluto'],
];

const jd = swe_julday(2000, 1, 1, 12.0, SE_GREG_CAL);
const planets = Object.fromEntries(
  PLANETS.map(([id, name]) => {
    const p = swe_calc_ut(jd, id, SEFLG_MOSEPH);
    return [name, { longitude: p.longitude, rc_flags: p.rc_flags }];
  }),
);
const nut = swe_calc_ut(jd, SE_ECL_NUT, 0);
const fixture = {
  source: 'Generated by scripts/generate-se-fixtures.mjs with Swiss Ephemeris 2.10.03 Moshier via @fusionstrings/swisseph-wasm. Instant: 2000-01-01 12:00:00 UTC (J2000 noon UT).',
  instant: '2000-01-01T12:00:00Z',
  julianDay: jd,
  sidtimeHours: swe_sidtime(jd),
  trueObliquity: nut.longitude,
  planets,
};

const outDir = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/chart/fixtures');
mkdirSync(outDir, { recursive: true });
const out = join(outDir, 'j2000-noon-ut.json');
writeFileSync(out, JSON.stringify(fixture, null, 2) + '\n');
console.log('wrote', out);
