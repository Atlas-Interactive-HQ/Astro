#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Body, Ecliptic, GeoVector, MakeTime, SiderealTime, e_tilt } from 'astronomy-engine';

const NAMES = [
  ['Sun', Body.Sun],
  ['Moon', Body.Moon],
  ['Mercury', Body.Mercury],
  ['Venus', Body.Venus],
  ['Mars', Body.Mars],
  ['Jupiter', Body.Jupiter],
  ['Saturn', Body.Saturn],
  ['Uranus', Body.Uranus],
  ['Neptune', Body.Neptune],
  ['Pluto', Body.Pluto],
];

const when = new Date('2000-01-01T12:00:00Z');
const time = MakeTime(when);
const planets = Object.fromEntries(
  NAMES.map(([name, body]) => {
    const ecl = Ecliptic(GeoVector(body, when, true));
    return [name, { longitude: ecl.elon, latitude: ecl.elat }];
  }),
);

const fixture = {
  source:
    'Generated by scripts/generate-atlas-fixtures.mjs with astronomy-engine. Instant: 2000-01-01 12:00:00 UTC (J2000 noon UT). Tropical ecliptic of date via GeoVector + Ecliptic.',
  library: 'astronomy-engine',
  instant: '2000-01-01T12:00:00Z',
  julianDay: 2451545 + time.ut,
  sidtimeHours: SiderealTime(time),
  trueObliquity: e_tilt(time).tobl,
  planets,
};

const outDir = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/chart/fixtures');
mkdirSync(outDir, { recursive: true });
const out = join(outDir, 'j2000-noon-ut.json');
writeFileSync(out, JSON.stringify(fixture, null, 2) + '\n');
console.log('wrote', out);
